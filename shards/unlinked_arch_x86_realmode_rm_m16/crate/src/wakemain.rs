#[inline(always)]
extern "C" fn __outb(mut value: u8, mut port: u16) {
unsafe {
core::arch::asm!("outb %al, %dx", in("ax") (value as u8) as u32, in("dx") port as u16, options(nostack, att_syntax));
}
}

#[inline(always)]
extern "C" fn __inb(mut port: u16) -> u8 {
let mut value: u8 = 0;
unsafe {
let __t0: u32;
core::arch::asm!("inb %dx, %al", lateout("ax") __t0, in("dx") port as u16, options(nostack, att_syntax));
value = unsafe { core::mem::transmute::<u8, u8>(__t0 as u8) };
}
value
}

#[inline(always)]
extern "C" fn __outw(mut value: u16, mut port: u16) {
unsafe {
core::arch::asm!("outw %ax, %dx", in("ax") value as u16, in("dx") port as u16, options(nostack, att_syntax));
}
}

#[repr(C)]
#[derive(Clone, Copy)]
struct port_io_ops {
    f_inb: Option<unsafe extern "C" fn(u16) -> u8>,
    f_outb: Option<unsafe extern "C" fn(u8, u16)>,
    f_outw: Option<unsafe extern "C" fn(u16, u16)>,
}


#[unsafe(no_mangle)]
static mut pio_ops: port_io_ops = unsafe { core::mem::zeroed() };

fn init_default_io_ops() {
unsafe {
pio_ops.f_inb = Some(__inb);
}
unsafe {
pio_ops.f_outb = Some(__outb);
}
unsafe {
pio_ops.f_outw = Some(__outw);
}
}

// Redirect port I/O operations via pio_ops callbacks.
// TDX guests override these callbacks with TDX-specific helpers.
fn io_delay() {
let DELAY_PORT: u16 = 128;
unsafe { unsafe { pio_ops.f_outb }.unwrap()(0u8, DELAY_PORT) };
}

fn udelay(mut loops: i32) {
loop {
let __v0: i32 = loops;
loops = __v0 - 1;
if __v0 == 0 {
break;
}
io_delay();
}
// Approximately 1 us
}

fn beep(hz: u32) {
let mut enable: u8 = 0;
if hz == 0 {
enable = 0; // Turn off speaker
} else {
let div: u16 = (1193181 / hz) as u16;
unsafe { unsafe { pio_ops.f_outb }.unwrap()(182u8, 67u16) }; // Ctr 2, squarewave, load, binary
io_delay();
unsafe { unsafe { pio_ops.f_outb }.unwrap()(div as u8, 66u16) }; // LSB of counter
io_delay();
unsafe { unsafe { pio_ops.f_outb }.unwrap()(((div as i32) >> 8i32) as u8, 66u16) }; // MSB of counter
io_delay();
enable = 3; // Turn on speaker
}
unsafe { unsafe { pio_ops.f_inb }.unwrap()(97u16) }; // Dummy read of System Control Port B
io_delay();
unsafe { unsafe { pio_ops.f_outb }.unwrap()(enable, 97u16) }; // Enable timer 2 output to speaker
io_delay();
}

