fn native_read_cr4() -> u64 {
let mut val: u64 = 0;
// CR4 always exists on x86_64.
unsafe {
let __t0: u64;
core::arch::asm!("mov %cr4,{0:r}", lateout(reg) __t0, options(nostack, att_syntax));
val = unsafe { core::mem::transmute::<u64, u64>(__t0 as u64) };
}
val
}

